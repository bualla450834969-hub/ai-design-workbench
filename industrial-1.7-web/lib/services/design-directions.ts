function ratioGuidance(r: number): string {
  // 把 0-100 映射成具体、可执行的强度描述，保证不同比例在视觉上有可感知差异
  const level = Math.max(0, Math.min(100, Math.round(r)));
  if (level === 0) {
    return "0%：几何轮廓、比例、体块、分件、特征面、部件数量和默认观察角度完全保持原产品不变；只允许按用户要求改变颜色、材质与表面工艺。只有用户明确要求换角度时才能改变观察角度，但产品几何仍必须保持不变。";
  }
  if (level <= 25) {
    return `${level}%：整体轮廓与比例基本保持不变；仅对局部细节、边缘倒角、表面纹理、局部开口或次要特征面做受控调整。约 ${level}% 的可识别造型特征允许改变。`;
  }
  if (level <= 50) {
    return `${level}%：在保持品类、核心功能和人机关系的前提下，调整约 ${level}% 的可识别造型特征，包括次要轮廓、体块切分、局部比例、分件方式、细节系统；主轮廓仍可被识别为同一品类，但已出现明确改款感。`;
  }
  if (level <= 75) {
    return `${level}%：大幅改款。必须主动改写主要轮廓、整体比例、主次体块关系、分件逻辑和至少一个标志性特征面；约 ${level}% 的可识别造型特征必须发生改变。保留品类、核心功能件与必要接口，但与原图并排时必须一眼看出是不同外观方案，严禁只做表面细节或CMF变化。`;
  }
  return `${level}%：激进重构，允许打破原有轮廓与体量关系，重新组织主次体块、分件方式和标志性特征面；约 ${level}% 的可识别造型特征必须发生改变。仍必须保持品类归属、核心功能、安全与人机可用性，禁止面目全非或结构不可信。`;
}

